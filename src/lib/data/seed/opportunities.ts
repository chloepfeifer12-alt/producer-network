import type { Opportunity } from "../types";
import { daysAgo } from "@/lib/utils/dates";

/**
 * Fictional opportunities. Compensation is shown ONLY as disclosed by the
 * fictional organization; there are no earnings projections or guarantees.
 */
type OppSeed = Omit<Opportunity, "createdAt" | "updatedAt" | "postedAt" | "isDemo" | "status" | "views"> & {
  posted: number;
  views: number;
  status?: Opportunity["status"];
};

function opp(o: OppSeed): Opportunity {
  const { posted, ...rest } = o;
  const status = o.status ?? "published";
  return {
    status,
    ...rest,
    postedAt: status === "published" || status === "archived" ? daysAgo(posted, 14) : undefined,
    createdAt: daysAgo(posted + 2, 11),
    updatedAt: daysAgo(posted, 14),
    isDemo: true,
  };
}

